"""Unit tests for .github/scripts/summarize_reports.py — the PR comment renderer.

Imported from the .github/scripts directory by path because it lives
outside the package on purpose (zero-dependency standalone script).
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / ".github" / "scripts" / "summarize_reports.py"

_spec = importlib.util.spec_from_file_location("summarize_reports", SCRIPT)
assert _spec and _spec.loader
_mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_mod)
summarize = _mod.summarize


