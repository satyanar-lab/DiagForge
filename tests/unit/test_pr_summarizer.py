def test_summarize_includes_top_hypothesis_and_mitigation(tmp_path: Path) -> None:
    path = _write_report(tmp_path, slug="p0300_intermittent_misfire")
    md = summarize(path)
    assert "### `p0300_intermittent_misfire`" in md
    assert "P0300" in md
    assert "Insufficient dematuration" in md
    assert "dematuration_timer" in md
    assert "dematuration_time_ms=1500" in md
    # Null parameter values are skipped from the inline list.
    assert "clear_threshold_offset" not in md


def test_summarize_includes_cross_dtc(tmp_path: Path) -> None:
    path = _write_report(tmp_path, slug="multi", with_cross=True)
    md = summarize(path)
    assert "Cross-DTC findings" in md
    assert "P0300 / P0301" in md


def test_main_writes_header_and_footer(tmp_path: Path, capsys) -> None:  # type: ignore[no-untyped-def]
    p = _write_report(tmp_path, slug="p0300_intermittent_misfire")
    rc = _mod.main([str(p)])
    out = capsys.readouterr().out
    assert rc == 0
    assert out.startswith("## DiagForge PR analysis")
    assert "Generated by" in out


def test_main_no_args_exits_usage(capsys) -> None:  # type: ignore[no-untyped-def]
    rc = _mod.main([])
    err = capsys.readouterr().err
    assert rc == 2
    assert "usage" in err
